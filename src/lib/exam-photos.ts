export function wikiPhotoUrl(fileName: string) {
  return `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(fileName)}?width=640`
}

export function unsplashPhotoUrl(id: string) {
  return `https://images.unsplash.com/photo-${id}?auto=format&fit=crop&w=640&h=640&q=80`
}

export function pexelsPhotoUrl(id: number) {
  return `https://images.pexels.com/photos/${id}/pexels-photo-${id}.jpeg?auto=compress&cs=tinysrgb&w=640`
}

export function examPhotoSources(scene: string) {
  const files = EXAM_PHOTO_FILES[scene] ?? []
  const remote: string[] = []
  if (scene === "flag-cn") {
    remote.push(
      "https://flagcdn.com/w320/cn.png",
      "https://upload.wikimedia.org/wikipedia/commons/thumb/f/fa/Flag_of_the_People%27s_Republic_of_China.svg/640px-Flag_of_the_People%27s_Republic_of_China.svg.png"
    )
  }
  const pexels = EXAM_PHOTO_PEXELS[scene]
  if (pexels) remote.push(pexelsPhotoUrl(pexels))
  remote.push(...files.map(wikiPhotoUrl))
  const unsplash = EXAM_PHOTO_UNSPLASH[scene]
  if (unsplash) remote.push(unsplashPhotoUrl(unsplash))
  return {
    local: `/exam-photos/${scene}.jpg`,
    remote,
  }
}
