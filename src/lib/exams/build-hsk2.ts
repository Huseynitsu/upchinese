export function buildHsk2(variant: number): OfficialPaper {
  const code = HSK2_CODES[variant]
  const tfItems = slice(LISTEN_PIC_TF, variant, 10).map((row, i) =>
    picTf(`${code}-ptf-${i + 1}`, i + 1, [{ text: row.audio }], row.picture, row.ok, true)
  )
  const listen = slice(LISTEN, variant, 25).map((row, i) =>
    mcq(`${code}-l-${i + 11}`, i + 11, duo(row.a, row.b, row.q), row.q, row.opts, row.key, true)
  )
  const reading = slice(READ, variant, 25).map((row, i) =>
    mcq(`${code}-r-${i + 36}`, i + 36, undefined, row.stem, row.opts, row.key)
  )
  return paper(2, code, 55, [
    block("listening", "一、听力", "Listening", 25, 35, [
      part("l1", "第一部分", "第 1–10 题：听句子，看图判断对错。", tfItems, undefined, PIC_TF_EXAMPLE),
      part("l2", "第二部分", "第 11–35 题：请选出正确答案。", listen),
    ]),
    block("reading", "二、阅读", "Reading", 22, 25, [
      part("r1", "第一部分", "第 36–60 题：请选出正确答案。", reading),
    ]),
  ], [
    "HSK（二级）分两部分：1. 听力（35题，约25分钟）2. 阅读（25题，22分钟）。",
    "听力播放两遍。全部考试约 55 分钟。",
  ])
}
