function firstPic(v: number) {
  const labels = PIC_LABELS[v][0]
  const pics = PICS[v][0]
  return pic(`h1-${CODES[v]}-21`, 21, undefined, pics, labels, PIC_KEYS[v][0], false)
}

export function buildHsk1(variant: number): OfficialPaper {
  const code = CODES[variant]
  const listenPicTf = LISTEN_PIC_TF[variant].map((row, i) =>
    picTf(`${code}-ptf-${i + 1}`, i + 1, [line(undefined, row.audio)], row.picture, row.ok, true)
  )
  const listenPics = PIC_AUDIO[variant].slice(5).map((text, i) =>
    pic(`${code}-p-${i + 6}`, i + 6, [line(undefined, text)], PICS[variant][i + 5], PIC_LABELS[variant][i + 5], PIC_KEYS[variant][i + 5], true)
  )
  const listenTf = TF[variant].map((row, i) =>
    tf(`${code}-tf-${i + 11}`, i + 11, [line(undefined, row[0])], row[1], row[2], true)
  )
  const listenMcq = LISTEN_MCQ[variant].map((row, i) =>
    mcq(
      `${code}-lm-${i + 16}`,
      i + 16,
      [
        { speaker: "女", text: row.a },
        { speaker: "男", text: row.b },
        { speaker: "问", text: row.q },
      ],
      row.q,
      row.opts,
      row.key,
      true
    )
  )
  const reading = [firstPic(variant), ...READ[variant].map((row, i) =>
    mcq(`${code}-r-${i + 22}`, i + 22, undefined, row.stem, row.opts, row.key)
  )]
  return paper(1, code, 40, [
    block("listening", "一、听力", "Listening", 15, 20, [
      part("l1", "第一部分", "第 1–5 题：听句子，看图判断对错。", listenPicTf, undefined, PIC_TF_EXAMPLE),
      part("l2", "第二部分", "第 6–10 题：听对话，选择对应的图片。", listenPics),
      part("l3", "第三部分", "第 11–15 题：判断对错。", listenTf),
      part("l4", "第四部分", "第 16–20 题：听对话，选出正确答案。", listenMcq),
    ]),
    block("reading", "二、阅读", "Reading", 17, 20, [
      part("r1", "第一部分", "第 21 题：看图选词。", [reading[0]]),
      part("r2", "第二部分", "第 22–40 题：请选出正确答案。", reading.slice(1)),
    ]),
  ], [
    "HSK（一级）分两部分：1. 听力（20题，约15分钟）2. 阅读（20题，17分钟）。",
    "听力播放两遍。全部考试约 40 分钟。",
    "听力由系统中文朗读生成，非官方版权录音。",
  ])
}

